# if statement
age = 18
if age >= 18:
    print("Eligible")

# if-else statement
age = 16
if age >= 18:
    print("Eligible")
else:
    print("Not Eligible")

# if-elif-else statement
marks = 75

if marks >= 90:
    print("Grade A")
elif marks >= 60:
    print("Grade B")
else:
    print("Grade C")

# Nested if statement
age = 21

if age >= 18:
    if age >= 21:
        print("Adult")